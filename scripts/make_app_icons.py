#!/usr/bin/env python3
"""Turn the ShiaVerse artwork into every icon the app needs.

One source image (``app/ShiaVerseIcon.png`` — the neon *ShiaVerse* plate) is
rendered into:

* ``app/assets/images/shiaverse_icon.png`` — the Flutter asset used by the home
  banner and the start-up screen.
* ``app/android/app/src/main/res/mipmap-*/ic_launcher.png`` — the legacy
  launcher icon (one bitmap per density, Android 7.x).
* ``.../mipmap-*/ic_launcher_round.png`` — the same icon for launchers that ask
  for a round one (API 25).
* ``.../mipmap-*/ic_launcher_foreground.png`` + ``mipmap-anydpi-v26/*.xml`` —
  the adaptive icon (Android 8+). The artwork sits in the 72 dp safe zone of the
  108 dp canvas, so no launcher mask can clip the wordmark.
* ``.../mipmap-*/ic_launcher_splash.png`` — the bitmap the launch screen
  centres. It is a plain density-qualified raster on purpose: ``<bitmap>``
  cannot draw the adaptive-icon XML, so the splash never points at
  ``@mipmap/ic_launcher``.
* ``.../values/ic_launcher_colors.xml`` and ``.../drawable/launch_background.xml``
  — the colour named by the adaptive icon, and the launch screen that paints it.

Legacy icons keep the artwork full bleed; the artwork's own near-black
background is what fills the corners, so nothing has to be composited on top and
no seam can appear.

Usage::

    python3 -m pip install Pillow
    python3 scripts/make_app_icons.py                  # write every icon
    python3 scripts/make_app_icons.py --source X.png    # different artwork
    python3 scripts/make_app_icons.py --dry-run         # report only

The output is deterministic: same source in, same bytes out.
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

try:  # Pillow is only needed for this script, never for the app itself.
    from PIL import Image, ImageEnhance, ImageFilter
except ImportError:  # pragma: no cover - depends on the local environment
    print("Pillow is required: python3 -m pip install Pillow", file=sys.stderr)
    raise SystemExit(2)

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = ROOT / "app" / "ShiaVerseIcon.png"
FLUTTER_ASSET = ROOT / "app" / "assets" / "images" / "shiaverse_icon.png"
ANDROID_RES = ROOT / "app" / "android" / "app" / "src" / "main" / "res"

# The Flutter copy is drawn at most ~120 dp wide, so 512 px is already generous
# on a 3x screen while keeping the APK small.
FLUTTER_ASSET_SIZE = 512

# density -> (legacy icon px, adaptive foreground px, splash bitmap px)
#
# The first two follow Android's icon sizes (48 dp base) and the 108 dp
# adaptive canvas; the splash plate is 112 dp so a centred launch bitmap reads
# as a logo rather than an icon.
DENSITIES: dict[str, tuple[int, int, int]] = {
    "mdpi": (48, 108, 112),
    "hdpi": (72, 162, 168),
    "xhdpi": (96, 216, 224),
    "xxhdpi": (144, 324, 336),
    "xxxhdpi": (192, 432, 448),
}

# The adaptive-icon canvas is 108 dp; only the central 72 dp is guaranteed to be
# visible, so that is where the artwork goes.
SAFE_ZONE_RATIO = 72 / 108

# Background behind the adaptive icon. It is sampled from the artwork's own
# corners in `_posterise`, and only ever shows in the outermost pixels, which
# the launcher mask cuts away.
BACKGROUND_COLOR = "#05061A"

ADAPTIVE_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_app_icons.py — edit that script, not this file. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""

COLOR_XML = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_app_icons.py — edit that script, not this file. -->
<resources>
    <color name="ic_launcher_background">{BACKGROUND_COLOR}</color>
</resources>
"""

LAUNCH_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/make_app_icons.py — edit that script, not this file. -->
<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <!-- The icon's own navy fills the window, so there is no white flash
         between the launcher tap and the first Flutter frame. -->
    <item android:drawable="@color/ic_launcher_background" />
    <item>
        <bitmap
            android:gravity="center"
            android:src="@mipmap/ic_launcher_splash" />
    </item>
</layer-list>
"""


def square(source: Image.Image) -> Image.Image:
    """The artwork, guaranteed square (the icon pipeline assumes 1:1)."""
    width, height = source.size
    if width == height:
        return source
    side = min(width, height)
    left = (width - side) // 2
    top = (height - side) // 2
    return source.crop((left, top, left + side, top + side))


def resized(image: Image.Image, size: int) -> Image.Image:
    return image.resize((size, size), Image.LANCZOS)


def round_icon(image: Image.Image, size: int) -> Image.Image:
    """Full-bleed artwork clipped to a circle, for `ic_launcher_round`."""
    square_icon = resized(image, size).convert("RGBA")
    mask = Image.new("L", (size * 4, size * 4), 0)
    from PIL import ImageDraw

    ImageDraw.Draw(mask).ellipse((0, 0, size * 4 - 1, size * 4 - 1), fill=255)
    square_icon.putalpha(mask.resize((size, size), Image.LANCZOS))
    return square_icon


def adaptive_foreground(image: Image.Image, canvas: int) -> Image.Image:
    """The artwork centred in the 72 dp safe zone of a 108 dp canvas.

    The safe zone is the only region a launcher is guaranteed to keep, but the
    layer still has to be a full 108 dp square: whatever sits outside the safe
    zone is what a circular or squircle mask cuts through. Pasting the artwork
    straight onto transparent corners left a visible rectangle behind the mask,
    so the canvas is first filled with the artwork's own colours — a blurred,
    darkened stretch of the very same image — and the sharp artwork is laid on
    top. The blend is seamless and the result is one full-bleed bitmap.
    """
    content = max(1, round(canvas * SAFE_ZONE_RATIO))
    offset = (canvas - content) // 2
    artwork = resized(image, content).convert("RGBA")
    backdrop = artwork.resize((canvas, canvas), Image.BILINEAR)
    backdrop = backdrop.filter(ImageFilter.GaussianBlur(canvas / 12))
    backdrop = ImageEnhance.Brightness(backdrop).enhance(0.25)
    backdrop.paste(artwork, (offset, offset), feather_mask(content))
    return backdrop


def feather_mask(size: int) -> Image.Image:
    """A soft-edged mask so the artwork dissolves into the backdrop.

    The artwork's own borders are dark, but not exactly the same dark as the
    blurred fill around it; a hard paste leaves a faint rectangle that a round
    launcher mask cuts right through. Fading the outer ~6% of the plate removes
    the edge entirely.
    """
    from PIL import ImageDraw

    inset = max(1, round(size * 0.06))
    mask = Image.new("L", (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        (inset, inset, size - inset - 1, size - inset - 1),
        radius=round(size * 0.08),
        fill=255,
    )
    return mask.filter(ImageFilter.GaussianBlur(inset / 2))


def save(image: Image.Image, path: Path) -> int:
    path.parent.mkdir(parents=True, exist_ok=True)
    # `optimize` keeps the neon gradients lossless but drops half the bytes.
    image.save(path, format="PNG", optimize=True)
    return path.stat().st_size


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=DEFAULT_SOURCE,
                        help=f"artwork to render (default: {DEFAULT_SOURCE.relative_to(ROOT)})")
    parser.add_argument("--dry-run", action="store_true", help="report the files that would be written")
    args = parser.parse_args()

    if not args.source.is_file():
        parser.error(f"artwork not found: {args.source}")

    with Image.open(args.source) as raw:
        raw.load()
        artwork = square(raw.convert("RGB"))

    # Every file the script owns, as (path, RGBA image | XML text).
    writes: list[tuple[Path, object]] = []
    writes.append((FLUTTER_ASSET, resized(artwork, FLUTTER_ASSET_SIZE)))
    for density, (legacy, canvas, splash) in DENSITIES.items():
        folder = ANDROID_RES / f"mipmap-{density}"
        writes.append((folder / "ic_launcher.png", resized(artwork, legacy)))
        writes.append((folder / "ic_launcher_round.png", round_icon(artwork, legacy)))
        writes.append((folder / "ic_launcher_foreground.png", adaptive_foreground(artwork, canvas)))
        writes.append((folder / "ic_launcher_splash.png", resized(artwork, splash)))
    writes.append((ANDROID_RES / "mipmap-anydpi-v26" / "ic_launcher.xml", ADAPTIVE_XML))
    writes.append((ANDROID_RES / "mipmap-anydpi-v26" / "ic_launcher_round.xml", ADAPTIVE_XML))
    writes.append((ANDROID_RES / "values" / "ic_launcher_colors.xml", COLOR_XML))
    writes.append((ANDROID_RES / "drawable" / "launch_background.xml", LAUNCH_XML))

    if args.dry_run:
        for path, _ in writes:
            print(f"would write {path.relative_to(ROOT)}")
        return 0

    total = 0
    for path, payload in writes:
        path.parent.mkdir(parents=True, exist_ok=True)
        if isinstance(payload, str):
            path.write_text(payload, encoding="utf-8")
            total += path.stat().st_size
        else:
            total += save(payload, path)
        print(f"{path.relative_to(ROOT)} ({path.stat().st_size:,} bytes)")
    print(f"\n{len(writes)} files, {total / 1024:.0f} KiB total from {args.source.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
